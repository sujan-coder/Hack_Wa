#define HID_KEY_ENTER   0x28
#define HID_KEY_TAB     0x2B

/* Convert ASCII char → modifier + keycode.  Returns false if unmappable. */
static inline bool ascii_to_hid(char c, uint8_t *mod, uint8_t *key)
{
    if (c == '\n' || c == '\r') { *mod = 0; *key = HID_KEY_ENTER; return true; }
    if (c == '\t')              { *mod = 0; *key = HID_KEY_TAB;   return true; }
    if (c < 32 || c > 126)     return false;
    const hid_keymap_t *e = &ASCII_TO_HID[(int)c - 32];
    *mod = e->mod;
    *key = e->key;
    return true;
}

